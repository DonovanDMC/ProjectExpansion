import { readFileSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, posix } from "node:path";

import { createScope } from "./context.ts";
import { childScope, evaluate, type Scope } from "./expression.ts";
import { Formats } from "./formats.ts";
import { Expanded, isPlainObject, MISSING, type Partial, Renderer, TemplateError } from "./template.ts";

export interface GenerateOptions {
    loader: string;
    templates: string;
    version: string;
}

export interface OutputFile {
    content: unknown;
    /** for merged files, which template set each key */
    keySources?: Map<string, string>;
    /** path in the output, after it's been adjusted for the version */
    path: string;
    sources: Array<string>;
}

const HEADER_KEYS = new Set(["$for", "$let", "$if", "$output", "$content"]);

async function listFiles(root: string): Promise<Array<string>> {
    const entries = await readdir(root, { recursive: true, withFileTypes: true });
    return entries
        .filter(entry => entry.isFile())
        .map(entry => posix.relative(root.replaceAll("\\", "/"), join(entry.parentPath, entry.name).replaceAll("\\", "/")))
        .toSorted();
}

function parseJson(text: string, file: string): unknown {
    try {
        return JSON.parse(text) as unknown;
    } catch (err) {
        throw new TemplateError(`${file}: ${(err as Error).message}`, { cause: err });
    }
}

/**
 * Renders every template for one Minecraft version. Templates mirror the 1.21 resource layout,
 * and are moved to wherever that version expects them.
 *
 * A template can start with a header:
 * - $for: {"name": "expr"}, renders the file once per value, later loops can use earlier ones
 * - $let: {"name": "expr"}, extra variables, evaluated in order
 * - $if: "expr", skips the file when false
 * - $output: "name", the file name to write, relative to the template's folder ("/" for the root)
 * - $content: the template itself
 *
 * Files and folders starting with "_" are partials, and aren't written. Files in a folder ending
 * with ".d" are merged into one file named after the folder, ex: lang/en_us.d/*.json -> lang/en_us.json
 */
export class Generator {
    private readonly partials = new Map<string, Partial>();
    readonly formats: Formats;
    readonly renderer: Renderer;
    readonly scope: Scope;

    constructor(readonly options: GenerateOptions) {
        this.formats = new Formats(options.version);
        this.scope = createScope(options.version, options.loader, this.formats);
        this.renderer = new Renderer(options.version, (ref, from) => this.loadPartial(ref, from));
    }

    private add(outputs: Map<string, OutputFile>, rawPath: string, source: string, content: unknown): void {
        const parts = rawPath.split("/");
        const mergeAt = parts.slice(0, -1).findIndex(part => part.endsWith(".d"));
        const merge = mergeAt !== -1;
        const resolved = merge ? `${[...parts.slice(0, mergeAt), parts[mergeAt]!.slice(0, -2)].join("/")}.json` : rawPath;
        let path: string;
        try {
            path = this.formats.path(resolved);
        } catch (err) {
            throw new TemplateError(`${source}: ${(err as Error).message}`, { cause: err });
        }

        const existing = outputs.get(path);
        if (existing === undefined) {
            outputs.set(path, {
                path,
                sources: [source],
                content,
                keySources: merge && isPlainObject(content) ? new Map(Object.keys(content).map(key => [key, source])) : undefined,
            });
            return;
        }
        if (!merge || existing.keySources === undefined || !isPlainObject(existing.content) || !isPlainObject(content)) {
            throw new TemplateError(`${source}: "${path}" was already generated by ${existing.sources.join(", ")}`);
        }
        for (const [key, value] of Object.entries(content)) {
            if (existing.keySources.has(key)) {
                throw new TemplateError(`${source}: "${key}" in "${path}" was already set by ${existing.keySources.get(key)}`);
            }
            existing.content[key] = value;
            existing.keySources.set(key, source);
        }
        existing.sources.push(source);
    }

    private evaluate(input: unknown, scope: Scope, file: string, at: string): unknown {
        if (typeof input !== "string") {
            return input;
        }
        try {
            return evaluate(input, scope);
        } catch (err) {
            throw new TemplateError(`${file} at ${at}: ${(err as Error).message}`, { cause: err });
        }
    }

    private lets(input: unknown, scope: Scope, file: string): Scope {
        if (input === undefined) {
            return scope;
        }
        if (!isPlainObject(input)) {
            throw new TemplateError(`${file}: $let must be an object of names to expressions`);
        }
        const local = childScope(scope, {});
        for (const [name, expression] of Object.entries(input)) {
            local[name] = this.evaluate(expression, local, file, `$let.${name}`);
        }
        return local;
    }

    private loadPartial(ref: string, from: string): Partial {
        let file = ref.startsWith("./") || ref.startsWith("../") ? posix.join(posix.dirname(from), ref) : posix.normalize(ref);
        if (!file.endsWith(".json")) {
            file += ".json";
        }
        let partial = this.partials.get(file);
        if (partial === undefined) {
            // partials are loaded while rendering, which is synchronous
            const parsed = parseJson(readFileSync(join(this.options.templates, file), "utf8"), file);
            if (isPlainObject(parsed) && "$content" in parsed) {
                const { $defaults = {}, $content, ...rest } = parsed;
                if (Object.keys(rest).length !== 0 || !isPlainObject($defaults)) {
                    throw new TemplateError(`${file}: partials can only have $defaults (an object) and $content`);
                }
                partial = { content: $content, defaults: $defaults, file };
            } else {
                partial = { content: parsed, defaults: {}, file };
            }
            this.partials.set(file, partial);
        }
        return partial;
    }

    private loops(input: unknown, scope: Scope, file: string): Array<Scope> {
        if (input === undefined) {
            return [scope];
        }
        if (!isPlainObject(input)) {
            throw new TemplateError(`${file}: $for must be an object of names to values`);
        }
        let scopes = [scope];
        for (const [name, source] of Object.entries(input)) {
            scopes = scopes.flatMap((current) => {
                let values = this.evaluate(source, current, file, `$for.${name}`);
                if (typeof values === "number") {
                    values = Array.from({ length: values }, (_, i) => i);
                }
                if (!Array.isArray(values)) {
                    throw new TemplateError(`${file} at $for.${name}: expected an array, got ${typeof values}`);
                }
                return values.map((value: unknown, index: number) => childScope(current, { [name]: value, [`${name}Index`]: index }));
            });
        }
        return scopes;
    }

    private outputPath(input: unknown, scope: Scope, file: string): string {
        if (input === undefined) {
            return file;
        }
        let name: unknown;
        try {
            name = typeof input === "string" ? this.renderer.renderString(input, scope) : input;
        } catch (err) {
            throw new TemplateError(`${file} at $output: ${(err as Error).message}`, { cause: err });
        }
        if (typeof name !== "string" || name.length === 0) {
            throw new TemplateError(`${file}: $output must render to a file name`);
        }
        const path = name.startsWith("/") ? name.slice(1) : posix.join(posix.dirname(file), name);
        return posix.normalize(path.endsWith(".json") ? path : `${path}.json`);
    }

    async generate(): Promise<Map<string, OutputFile>> {
        const outputs = new Map<string, OutputFile>();
        for (const file of await listFiles(this.options.templates)) {
            if (file.split("/").some(part => part.startsWith("_"))) {
                continue;
            }
            if (!file.endsWith(".json")) {
                this.add(outputs, file, file, await readFile(join(this.options.templates, file)));
                continue;
            }
            const template = parseJson(await readFile(join(this.options.templates, file), "utf8"), file);
            for (const [path, content] of this.renderFile(template, file)) {
                this.add(outputs, path, file, content);
            }
        }
        return outputs;
    }

    /** renders one template, returning [path, content] for each file it makes */
    renderFile(template: unknown, file: string): Array<[string, unknown]> {
        const hasHeader = isPlainObject(template) && "$content" in template;
        const header = hasHeader ? template : { $content: template };
        const unknown = Object.keys(header).filter(key => !HEADER_KEYS.has(key));
        if (unknown.length !== 0) {
            throw new TemplateError(`${file}: Unknown header keys: ${unknown.join(", ")}`);
        }

        const files: Array<[string, unknown]> = [];
        for (const scope of this.loops(header.$for, this.scope, file)) {
            const local = this.lets(header.$let, scope, file);
            if (header.$if !== undefined && !this.evaluate(header.$if, local, file, "$if")) {
                continue;
            }
            const content = this.renderer.render(header.$content, local, file);
            if (content === MISSING) {
                continue;
            }
            files.push([this.outputPath(header.$output, local, file), content instanceof Expanded ? content.values : content]);
        }
        return files;
    }
}

/** writes the outputs into a clean directory */
export async function writeOutputs(outputs: Map<string, OutputFile>, directory: string): Promise<void> {
    await rm(directory, { recursive: true, force: true });
    for (const file of outputs.values()) {
        const target = join(directory, file.path);
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, file.content instanceof Uint8Array ? file.content : `${JSON.stringify(file.content, null, "\t")}\n`);
    }
}
